function chunkFrom(
  docId: string,
  section: string,
  needle: string,
  extra = 80,
): Chunk {
  const document = DOCUMENTS.find((d) => d.id === docId);
  if (!document) throw new Error(`missing doc ${docId}`);
  const idx = document.text.indexOf(needle);
  if (idx < 0) throw new Error(`needle not found in ${docId}: ${needle}`);
  const charStart = Math.max(0, idx - extra);
  const charEnd = Math.min(document.text.length, idx + needle.length + extra);
  const tsMatch = document.text.slice(charStart, charEnd).match(/\[(\d{2}:\d{2}:\d{2})\]/);
  return {
    id: `${docId}:${charStart}-${charEnd}`,
    docId,
    ticker: document.ticker,
    quarter: document.quarter,
    docType: document.docType,
    section,
    charStart,
    charEnd,
    timestamp: document.docType === "transcript" ? tsMatch?.[1] : undefined,
    text: document.text.slice(charStart, charEnd).replace(/\s+/g, " ").trim(),
    table: /Net sales|Revenue\s|Diluted EPS|in millions/i.test(needle),
  };
}

